export type ProcVerdict = "windows" | "known" | "unknown";

export interface ProcInfo {
  what: string;
  verdict: ProcVerdict;
  /** Why there may be many of these, when that is normal. */
  why?: string;
  /** What one connection of this program is usually doing. */
  each?: string;
  verdictText: string;
}

